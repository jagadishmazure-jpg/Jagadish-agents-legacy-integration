"""Regenerate docs/results.md and the README results block from results.json and the real test count.

python scripts/render_docs.py          # rewrite
python scripts/render_docs.py --check  # fail if the committed docs are stale (CI)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from count_tests import count  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- results:start -->", "<!-- results:end -->"


def block(r: dict, tests: int) -> str:
    lat, rt, o, idem, sd, mq, rl, ag = (
        r[k]
        for k in ("latency", "copybook_roundtrip", "outage", "idempotency", "screen_drift", "mq_faults", "rate_limit", "agent")
    )
    names = {
        "cobol_direct": "COBOL program call (ACCTINQ)",
        "rest_facade": "REST API facade -> COBOL",
        "mq_request_reply": "MQ request/reply -> COBOL (POLINQ)",
        "screen_scrape": "5250 screen scrape (sign-on to detail)",
        "sql_db2i": "DB2-for-i style SQL (SQLite)",
        "batch_100_accounts": "Batch file drop, 100 accounts (ACCTBAT)",
    }
    rows = "\n".join(f"| {names[k]} | {lat[k]['n']} | {lat[k]['p50_ms']} | {lat[k]['p95_ms']} |" for k in names)
    cdc = lat["cdc_event_lag"]
    drift = "\n".join(
        f"| {v} | {sd[v]['reads']} | {sd[v]['naive_silently_wrong']} | {sd[v]['guarded_detected_drift']} | "
        f"{sd[v]['guarded_wrong']} | {sd[v]['relocated_correct']} |"
        for v in ("v1", "v2", "v3")
    )
    return f"""{START}
**Tests: {tests}** (pytest, all passing). Numbers below come from `legacyagents bench` on one Linux machine;
latency varies by machine, every other number is deterministic and checked in CI.

| Pattern | Calls | p50 ms | p95 ms |
| --- | --- | --- | --- |
{rows}

Batch cost per account: {lat["batch_per_account_ms"]} ms. CDC event lag (journal write to agent): p50 {cdc["p50_ms"]} ms,
max {cdc["max_ms"]} ms over {cdc["n"]} changes.

| Check | Result |
| --- | --- |
| Copybook round trip, {rt["random_records"]:,} random account records (dict, bytes, EBCDIC) | {rt["ascii_dict_roundtrip"]:,} / {rt["byte_roundtrip"]:,} / {rt["ebcdic_roundtrip"]:,} ({rt["accuracy_pct"]}%) |
| Records read back by the compiled COBOL program equal the source | {rt["cobol_read_matches"]} |
| Policy records round trip | {rt["policy_roundtrip"]} |
| Outage: {o["requests_during_outage"]} questions while COBOL is down | {o["calls_that_reached_legacy"]} reached legacy, {o["short_circuited"]} short-circuited, {o["safe_answers"]} safe answers, {o["wrong_answers"]} wrong |
| Recovery after breaker cooldown | {o["recovered_after_cooldown"]} (breaker {o["breaker_after"]}) |
| Idempotency: {idem["write_attempts"]} write attempts for {idem["unique_writes"]} unique writes | {idem["applied"]} applied, {idem["duplicates_prevented"]} duplicates prevented |
| MQ with {int(mq["drop_rate"] * 100)}% of requests dropped, {mq["requests"]} requests | {mq["answered_correctly"]} answered correctly in {mq["attempts"]} attempts, {mq["gave_up"]} gave up |
| Rate limit: burst of {rl["burst_requests"]} against a bucket of {rl["burst_size"]} | {rl["allowed"]} allowed, {rl["rejected"]} rejected, {rl["legacy_calls"]} legacy calls |
| Agent routing, {ag["cases"]} labelled questions (regression check) | {ag["routed_correctly"]}/{ag["cases"]} |
| Writes without human approval | {ag["writes_without_approval"]} |
| Planted PII values found in audit log or trace | {ag["pii_leaks_in_logs"]} of {ag["planted_pii_values"]} |

Screen layout drift ({sd["v1"]["reads"]} reads per layout; v2 shifts fields, v3 renames a label):

| Layout | Reads | Naive scraper silently wrong | Guarded scraper detected drift | Guarded wrong | Relocate-by-label correct |
| --- | --- | --- | --- | --- | --- |
{drift}

Write guardrails: read-only tool refused = {sd["writes"]["read_only_refused"]}, no approval leaves it pending =
{sd["writes"]["no_approval_pending"]}, write on a drifted screen refused = {sd["writes"]["write_on_drifted_screen_refused"]}.
{END}"""


def render() -> dict[Path, str]:
    r = json.loads((ROOT / "results.json").read_text())
    b = block(r, count())
    readme = (ROOT / "README.md").read_text()
    readme = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: b, readme, flags=re.S)
    results = (
        "# Measured results\n\nGenerated by `scripts/render_docs.py` from `results.json`. Do not edit by hand.\n\n" + b + "\n"
    )
    return {ROOT / "README.md": readme, ROOT / "docs" / "results.md": results}


if __name__ == "__main__":
    out = render()
    if "--check" in sys.argv:
        stale = [p.name for p, t in out.items() if not p.exists() or p.read_text() != t]
        if stale:
            sys.exit(f"stale docs: {stale}; run python scripts/render_docs.py")
        print("docs match results.json and the real test count")
    else:
        for p, t in out.items():
            p.write_text(t)
        print("docs rendered")
